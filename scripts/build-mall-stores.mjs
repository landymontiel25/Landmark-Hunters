// Builds src/data/mallStores.js: every mall in the app and the stores inside
// it, from the research files in scripts/osm-import/research/malls/:
//   stores.json       the big malls (Dadeland, Dolphin Mall, King of Prussia...)
//   stores-more.json  every other mall already in the app
//   (any other .json there too: a later import's malls)
// Each mall is a place already in the catalog (key "<region>/<id>"); each
// store comes from a result that names it at that mall (its `source`).
// A mall is a catalog place with topic 'mall' (imports) or `mall: true`
// (hand-picked); src/data/mallStores.test.js fails while any mall has no
// stores here, so a newly added mall can't ship without its store list.
//   node scripts/build-mall-stores.mjs
import fs from 'node:fs';

const DIR = 'scripts/osm-import/research/malls';
const TAGS = new Set(['clothing', 'shoes', 'department store', 'beauty', 'electronics', 'books', 'home', 'sports', 'toys', 'jewelry', 'coffee', 'cafe', 'food', 'fast food', 'dessert', 'entertainment', 'fitness', 'pets', 'gifts', 'luxury', 'grocery', 'pharmacy']);
// The first research file has no city; these are the malls' own towns.
const CITY = {
  'miami/osm-w144051823': 'Kendall, Miami',
  'miami/dolphin-mall': 'Sweetwater, Miami',
  'miami/brickell-city-centre': 'Brickell, Miami',
  'miami/bayside-marketplace': 'Downtown Miami',
  'miami/osm-w291775638': 'Coral Gables',
  'philly/king-of-prussia-mall': 'King of Prussia, PA',
  'silicon-valley/santana-row': 'San Jose, CA',
};

const rows = [];
// Every research file in the folder (stores.json first), so a new import's
// malls just add a file.
const files = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort((a, b) => (a === 'stores.json' ? -1 : b === 'stores.json' ? 1 : a.localeCompare(b))) : [];
for (const f of files) rows.push(...JSON.parse(fs.readFileSync(`${DIR}/${f}`, 'utf8')));
const seen = new Set();
const malls = [];
for (const m of rows) {
  if (!m?.key || seen.has(m.key)) continue;
  const stores = [];
  const names = new Set();
  for (const s of m.stores || []) {
    const name = String(s.name || '').trim();
    const tags = (s.tags || []).filter((t) => TAGS.has(t)).slice(0, 2);
    if (!name || !tags.length || names.has(name.toLowerCase())) continue;
    names.add(name.toLowerCase());
    stores.push({ name, tags, ...(s.source && s.source !== m.source ? { source: s.source } : {}) });
  }
  if (!stores.length) continue;
  seen.add(m.key);
  malls.push({ key: m.key, mall: m.mall, city: m.city || CITY[m.key] || '', source: m.source, stores });
}

fs.writeFileSync(
  'src/data/mallStores.js',
  `// Every mall in the app and the stores inside it, as the mall's own
// directory (or another result, its \`source\`) lists them. A mall is keyed
// by its catalog place ("<region>/<id>"); lib/malls.js storesOfPlace reads it.
// Generated by scripts/build-mall-stores.mjs from
// scripts/osm-import/research/malls/; edit those, not this file.
export const MALL_STORES = ${JSON.stringify(malls, null, 2)};
`
);
console.log(malls.map((m) => `${m.mall}: ${m.stores.length}`).join('\n'));
